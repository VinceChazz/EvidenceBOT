"""Transparent, rule-based evidence strength classification.

Grades are derived from study design, number of relevant studies, source
quality, consistency of findings, directness of the evidence and full-text
availability. The composite score is an explicit rule-based index on a 0-1
scale — it is **not** a probability and it is never produced by an LLM.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from typing import Any, Dict, List, Sequence

from evidence.evidence_evaluator import EvidenceAssessment
from processing.models import Passage, SOURCE_TYPE_WEIGHTS
from utils.helpers import clamp
from utils.logging_config import get_logger

logger = get_logger("evidence.strength")

STRONG = "strong"
MODERATE = "moderate"
LIMITED = "limited"
CONFLICTING = "conflicting"
INSUFFICIENT = "insufficient"

GRADE_LABELS = {
    STRONG: "Strong supporting evidence",
    MODERATE: "Moderate supporting evidence",
    LIMITED: "Limited evidence",
    CONFLICTING: "Conflicting evidence",
    INSUFFICIENT: "Insufficient evidence",
}

GRADE_COLORS = {
    STRONG: "#12805c",
    MODERATE: "#1d6fa5",
    LIMITED: "#b8860b",
    CONFLICTING: "#b45309",
    INSUFFICIENT: "#7c3aed",
}

STUDY_DESIGN_LABELS = {
    "systematic_review": "systematic review",
    "meta_analysis": "meta-analysis",
    "randomized_controlled_trial": "randomised controlled trial",
    "clinical_trial": "clinical trial",
    "cohort_study": "prospective cohort study",
    "case_control_study": "case-control study",
    "observational_study": "observational study",
    "peer_reviewed_article": "peer-reviewed research article",
    "review": "narrative review",
    "conference_paper": "conference paper",
    "preprint": "preprint",
    "book_chapter": "book chapter",
    "background": "background material",
    "unknown": "unclassified record",
}


@dataclass
class StrengthComponent:
    name: str
    score: float
    weight: float
    detail: str

    def to_dict(self) -> Dict[str, Any]:
        return {
            "component": self.name,
            "score": round(self.score, 3),
            "weight": self.weight,
            "weighted": round(self.score * self.weight, 3),
            "detail": self.detail,
        }


@dataclass
class EvidenceStrength:
    grade: str
    label: str
    color: str
    score: float
    components: List[StrengthComponent] = field(default_factory=list)
    reasons: List[str] = field(default_factory=list)
    cautions: List[str] = field(default_factory=list)
    study_designs: List[str] = field(default_factory=list)
    study_count: int = 0

    @property
    def is_insufficient(self) -> bool:
        return self.grade == INSUFFICIENT

    def to_dict(self) -> Dict[str, Any]:
        return {
            "grade": self.grade,
            "label": self.label,
            "score": round(self.score, 3),
            "components": [c.to_dict() for c in self.components],
            "reasons": self.reasons,
            "cautions": self.cautions,
            "study_designs": self.study_designs,
            "study_count": self.study_count,
            "note": (
                "Rule-based composite index (0-1) computed from study design, study "
                "count, source quality, consistency, directness and full-text "
                "availability. It is not a probability and is not generated by an LLM."
            ),
        }


def assess_evidence_strength(assessment: EvidenceAssessment) -> EvidenceStrength:
    """Grade the evidence behind an :class:`EvidenceAssessment`."""

    passages: Sequence[Passage] = assessment.supported_passages
    if assessment.is_abstention or not passages:
        return EvidenceStrength(
            grade=INSUFFICIENT,
            label=GRADE_LABELS[INSUFFICIENT],
            color=GRADE_COLORS[INSUFFICIENT],
            score=0.0,
            reasons=[assessment.reason],
            cautions=["No usable evidence passed the evidence gate."],
        )

    # ---------------------------------------------------------- study design
    design_scores = [SOURCE_TYPE_WEIGHTS.get(p.source_type, 0.4) for p in passages]
    best_design = max(design_scores)
    mean_design = sum(design_scores) / len(design_scores)
    design_score = clamp(0.6 * best_design + 0.4 * mean_design)

    # --------------------------------------------------------- study count
    count_score = clamp(len({p.document_id for p in passages}) / 4.0)

    # ------------------------------------------------------- source quality
    peer_reviewed = sum(1 for p in passages if p.is_peer_reviewed and not p.is_preprint)
    quality_ratio = peer_reviewed / len(passages)
    synthesis_bonus = 0.15 if any(
        p.source_type in {"meta_analysis", "systematic_review"} for p in passages
    ) else 0.0
    quality_score = clamp(quality_ratio + synthesis_bonus)

    # ---------------------------------------------------------- consistency
    consistency_map = {
        "consistent_support": 1.0,
        "consistent_null": 0.8,
        "mixed": 0.45,
        "conflicting": 0.2,
        "inconclusive": 0.5,
    }
    consistency_score = consistency_map.get(assessment.consistency.conclusion, 0.5)

    # ----------------------------------------------------------- directness
    directness_score = clamp(assessment.sufficiency.get("question_coverage", 0.0))

    # -------------------------------------------------------- full text
    full_text_ratio = sum(1 for p in passages if p.provenance == "abstract+full_text") / len(
        passages
    )
    fulltext_score = clamp(0.35 + 0.65 * full_text_ratio)

    components = [
        StrengthComponent("Study design", design_score, 0.30,
                          f"Strongest design: {STUDY_DESIGN_LABELS.get(passages[0].source_type, 'mixed')}"),
        StrengthComponent("Number of relevant studies", count_score, 0.20,
                          f"{len({p.document_id for p in passages})} distinct publication(s)"),
        StrengthComponent("Source quality", quality_score, 0.20,
                          f"{peer_reviewed}/{len(passages)} passage(s) from peer-reviewed sources"),
        StrengthComponent("Consistency of findings", consistency_score, 0.15,
                          assessment.consistency.label),
        StrengthComponent("Directness of evidence", directness_score, 0.10,
                          f"Question concept coverage {assessment.sufficiency.get('question_coverage', 0):.2f}"),
        StrengthComponent("Full-text availability", fulltext_score, 0.05,
                          f"{sum(1 for p in passages if p.provenance == 'abstract+full_text')} of "
                          f"{len(passages)} passage(s) from full text"),
    ]
    score = sum(c.score * c.weight for c in components)

    # ------------------------------------------------------------- grading
    reasons: List[str] = []
    cautions: List[str] = list(assessment.notes)
    designs = sorted({STUDY_DESIGN_LABELS.get(p.source_type, p.source_type) for p in passages})
    distinct_studies = len({p.document_id for p in passages})

    if assessment.consistency.is_conflicting:
        grade = CONFLICTING
        reasons.append(assessment.consistency.label + ".")
    elif score >= 0.72 and distinct_studies >= 3 and consistency_score >= 0.9:
        grade = STRONG
        reasons.append(
            f"{distinct_studies} consistent publications including "
            f"{', '.join(designs[:3])}."
        )
    elif score >= 0.52:
        grade = MODERATE
        reasons.append(f"Relevant evidence from {distinct_studies} publication(s).")
    elif score >= 0.30:
        grade = LIMITED
        reasons.append("Evidence is thin, indirect, or based on weak study designs.")
    else:
        grade = LIMITED
        reasons.append("Very limited evidence; interpret with caution.")

    if peer_reviewed == 0:
        cautions.append("No peer-reviewed source supports this answer (preprints only).")
    if assessment.causal_claim and not any(
        p.source_type in {"randomized_controlled_trial", "clinical_trial"} for p in passages
    ):
        cautions.append("Causal wording is not supported by interventional designs.")
    if any(p.is_sample for p in passages):
        cautions.append(
            "These passages come from the illustrative offline sample corpus, not live literature."
        )
    if assessment.is_partial:
        reasons.append("The evidence covers only part of the question.")

    strength = EvidenceStrength(
        grade=grade,
        label=GRADE_LABELS[grade],
        color=GRADE_COLORS[grade],
        score=round(score, 3),
        components=components,
        reasons=reasons,
        cautions=cautions,
        study_designs=designs,
        study_count=distinct_studies,
    )
    logger.info("evidence strength=%s score=%.3f", grade, score)
    return strength


def strength_from_passages(passages: Sequence[Passage]) -> EvidenceStrength:
    """Convenience helper used by tests: grade a raw passage list."""

    from evidence.evidence_evaluator import EvidenceEvaluator

    settings = _default_settings()
    evaluator = EvidenceEvaluator(settings)
    assessment = evaluator.evaluate(
        "evidence strength", list(passages), ranking_stats={}
    )
    return assess_evidence_strength(assessment)


def _default_settings():
    from config import Settings

    return Settings()
